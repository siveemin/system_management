export type TranslationKey = keyof typeof translations.en;
export type Translations = typeof translations.en;

export function getTranslations(lang: Language): Translations {
  return translations[lang] as Translations;
}

// Module-level cache so non-React code can call t() too
let _lang: Language = "en";
export function setActiveLanguage(lang: Language) { _lang = lang; }
export function getActiveLanguage(): Language { return _lang; }
export function t(key: TranslationKey): string {
  return (translations[_lang] as any)[key] ?? (translations.en as any)[key] ?? key;
}
